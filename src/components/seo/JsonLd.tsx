// Renders one or more JSON-LD blocks. `data` is trusted, server-built schema.org
// objects (never raw user input) — see src/lib/schema.ts for the builders.
export function JsonLd({ data }: { data: object | object[] }) {
  const items = Array.isArray(data) ? data : [data];
  return (
    <>
      {items.map((item, i) => (
        <script
          key={i}
          type="application/ld+json"
          dangerouslySetInnerHTML={{ __html: JSON.stringify(item) }}
        />
      ))}
    </>
  );
}
